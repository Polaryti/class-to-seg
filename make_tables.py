#!/usr/bin/env python3
"""Turn the aggregated results into the LaTeX tables and number macros of the manuscript.

Every table body is a complete tabular written to <out>/tab_*.tex; the manuscript keeps the
caption and the label and includes the body. Numbers quoted in the text come from
<out>/results_macros.tex through \\res{key}{field}. Missing values print \\TBD, so this can be
run at any stage, including before any experiment has finished.

Example
-------
python make_tables.py --results /scratch/results --protocol /scratch/protocol --out ../paper/tables
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from common import read_csv

DEFAULT_NAMES = ["SIGRE", "blue", "brown", "green", "green_point", "grey", "yellow"]
ABBR = {"SIGRE": "SIG", "blue": "Blu", "brown": "Bro", "green": "Gre", "green_point": "GP", "grey": "Gry", "yellow": "Yel"}
DISPLAY = {"green_point": "green point"}
MAIN_BLOCKS = [("v1", ["E1", "E2", "E3", "E4", "E5"]), ("v2", ["E6", "E7", "E8", "E9", "E10"]),
               ("v3", ["E11", "E12", "E13", "E14", "E15"])]
CONTROLS = [("E16", "Copy-paste, $p=0.3$"), ("E19", "Size-matched to v1"), ("E20", "Deranged generated labels"),
            ("E17", "YOLOv8m-seg"), ("E18", "Mask R-CNN R50-FPN")]
COMPARISONS = [("E13", "E3", "v3 vs.\\ v1"), ("E13", "E8", "v3 vs.\\ v2"), ("E3", "E8", "v1 vs.\\ v2"),
               ("E19", "E3", "v3 size-matched vs.\\ v1"), ("E19", "E13", "v3 size-matched vs.\\ v3"),
               ("E20", "E13", "Deranged labels vs.\\ v3"), ("E16", "E13", "Copy-paste vs.\\ v3"),
               ("E17", "E13", "YOLOv8m vs.\\ YOLO11m"), ("E18", "E13", "Mask R-CNN vs.\\ YOLO11m"),
               ("E14", "E13", "Large vs.\\ medium scale"), ("E11", "E13", "Nano vs.\\ medium scale"),
               ("E21", "E13", "Focal-loss run vs.\\ v3"), ("E22", "E13", "Class-weight run vs.\\ v3")]
PERCLASS_IDS = [("E3", "v1"), ("E8", "v2"), ("E13", "v3"), ("E16", "CP"), ("E19", "SM"), ("E20", "DL")]
ORIGIN_IDS = ["E3", "E8", "E13", "E19", "E20", "E18"]
SCALES = [("E11", "n"), ("E12", "s"), ("E13", "m"), ("E14", "l"), ("E15", "x")]
TBD = "\\TBD"


def num(x):
    try:
        v = float(x)
        return None if math.isnan(v) else v
    except (TypeError, ValueError):
        return None


def f(x, d=4):
    v = num(x)
    return TBD if v is None else f"{v:.{d}f}"


def fint(x):
    v = num(x)
    return TBD if v is None else f"{int(round(v)):,}"


def fpct(x, d=1):
    v = num(x)
    return TBD if v is None else f"{100 * v:.{d}f}"


def fsigned(x, d=4):
    v = num(x)
    return TBD if v is None else f"{v:+.{d}f}"


def pm(mean, sd, d=4):
    m, s = num(mean), num(sd)
    if m is None:
        return TBD
    return f"${m:.{d}f} \\pm {s:.{d}f}$" if s is not None else f"${m:.{d}f}$"


def ftau(x):
    v = num(x)
    if v is None:
        return TBD
    t = f"{v:.3f}".rstrip("0")
    return t + "0" * max(0, 4 - len(t))


def eid_tex(e):
    return f"$E_{{{e[1:]}}}$"


def disp(n):
    return DISPLAY.get(n, n)


def load_json(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def load_rows(p):
    p = Path(p)
    return read_csv(p) if p.exists() else []


def write(path, text):
    Path(path).write_text("% Generated by make_tables.py -- do not edit by hand.\n" + text + "\n")


class Macros:
    def __init__(self):
        self.items = {}

    def set(self, key, field, value):
        if value is None or value == TBD:
            return
        self.items[(str(key), str(field))] = str(value)

    def write(self, path):
        lines = ["% Generated by make_tables.py -- do not edit by hand.",
                 "% Usage in the manuscript: \\res{key}{field}; undefined entries print \\TBD."]
        for (k, fl), v in sorted(self.items.items()):
            lines.append(f"\\expandafter\\def\\csname res@{k}@{fl}\\endcsname{{{v}}}")
        Path(path).write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", required=True)
    ap.add_argument("--protocol", default=None)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    R, out = Path(a.results), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    M = Macros()

    met = {(r["id"], r["eval_set"], r["metric"]): r for r in load_rows(R / "metrics.csv")}
    per_class = {(r["id"], r["eval_set"], r["class"]): r for r in load_rows(R / "per_class.csv")}
    comp = {(r["a"], r["b"], r["eval_set"], r["metric"]): r for r in load_rows(R / "comparisons.csv")}
    models = {r["id"]: r for r in load_rows(R / "models.csv")}
    cstats = load_json(R / "corpus_stats.json") or {}
    proto = load_json(Path(a.protocol) / "protocol_summary.json") if a.protocol else None
    names = DEFAULT_NAMES
    for k in ("v3", "v1", "v2"):
        if k in cstats:
            names = cstats[k]["names"]
            break

    def mv(eid, metric, es="common", field="mean"):
        r = met.get((eid, es, metric))
        return r.get(field) if r else None

    # ----------------------------------------------------------------- macros: results
    for (eid, es, metric), r in met.items():
        pre = "" if es == "common" else es.split("_")[0] + "_"
        M.set(eid, pre + metric, f(r["mean"]))
        M.set(eid, pre + "sd_" + metric, f(r["sd_folds"]))
        M.set(eid, pre + "sd_seeds_" + metric, f(r.get("sd_seeds")))
        if es == "common" and metric == "mAP50_95":
            M.set(eid, "sd_seeds", f(r.get("sd_seeds")))
        M.set(eid, "runs", fint(r.get("n_runs")))
        M.set(eid, "folds", fint(r.get("n_folds")))
    for (eid, es, cls), r in per_class.items():
        pre = "" if es == "common" else es.split("_")[0] + "_"
        M.set(eid, f"{pre}AP_{cls}", f(r["mean"], 3))
        M.set(eid, f"{pre}sd_AP_{cls}", f(r["sd_folds"], 3))
    for (x, y, es, metric), r in comp.items():
        if es != "common":
            continue
        k = f"{x}-{y}"
        M.set(k, f"d_{metric}", fsigned(r["delta"]))
        M.set(k, f"lo_{metric}", fsigned(r["ci_low"]))
        M.set(k, f"hi_{metric}", fsigned(r["ci_high"]))
        p = num(r.get("p_paired_t"))
        if p is not None:
            M.set(k, f"p_{metric}", "{<}0.001" if p < 0.001 else f"= {p:.3f}")
        ph = num(r.get("p_holm"))
        if ph is not None:
            M.set(k, f"pholm_{metric}", "{<}0.001" if ph < 0.001 else f"= {ph:.3f}")
        M.set(k, "nfolds", fint(r.get("n_folds")))
        M.set(k, "positive_folds", fint(r.get("positive_folds")))
    ended = {k: sum(num(r.get(f"runs_{k}")) or 0 for r in models.values())
             for k in ("full", "patience", "interrupted", "unknown")}
    M.set("protocol", "runs_full", fint(ended["full"]))
    M.set("protocol", "runs_patience", fint(ended["patience"]))
    # whatever is neither complete nor stopped by patience ended early, including the few runs
    # whose results.csv could not be read, so that the three counts add up to the total
    total_runs = sum(num(r.get("runs")) or 0 for r in models.values())
    M.set("protocol", "runs_short", fint(total_runs - ended["full"] - ended["patience"]) if models else None)
    for eid, r in models.items():
        p = num(r.get("params"))
        M.set(eid, "params", f"{p / 1e6:.1f}" if p else None)
        M.set(eid, "gflops", f(r.get("gflops"), 1))
        M.set(eid, "size", f(r.get("size_mb"), 1))
        M.set(eid, "lat", f(r.get("latency_ms_median"), 1))
        M.set(eid, "epochs_mean", f(r.get("epochs_mean"), 0))
        M.set(eid, "short_runs", fint(r.get("runs_below_300_epochs")))
        for k in ("full", "patience", "interrupted"):
            M.set(eid, f"runs_{k}", fint(r.get(f"runs_{k}")))
    best = {}
    for block, ids in MAIN_BLOCKS:
        vals = [(num(mv(e, "mAP50_95")), e) for e in ids]
        vals = [v for v in vals if v[0] is not None]
        if vals:
            v, e = max(vals)
            best[block] = (v, e)
            M.set(f"best_{block}", "id", f"E_{{{e[1:]}}}")
            M.set(f"best_{block}", "mAP50_95", f(v))
            M.set(f"best_{block}", "sd_mAP50_95", f(mv(e, "mAP50_95", field="sd_folds")))
            for metric in ("mAP50", "P", "R"):
                M.set(f"best_{block}", metric, f(mv(e, metric)))
    if "v1" in best and best["v1"][0]:
        if "v3" in best:
            M.set("rel", "v3_vs_v1", f"{100 * (best['v3'][0] - best['v1'][0]) / best['v1'][0]:.1f}")
        if "v2" in best:
            M.set("rel", "v2_vs_v1", f"{100 * (best['v1'][0] - best['v2'][0]) / best['v1'][0]:.1f}")

    # ----------------------------------------------------------------- main results
    lines = ["\\begin{tabular}{@{}lll" + "c" * 4 + "@{}}", "\\hline",
             "\\textbf{\\#} & \\textbf{Corpus} & \\textbf{Scale} & \\textbf{P} & \\textbf{R} & \\textbf{mAP50} & "
             "\\textbf{mAP50-95} \\\\", "\\hline"]
    allv = {m: [num(mv(e, m)) for _, ids in MAIN_BLOCKS for e in ids] for m in ("P", "R", "mAP50", "mAP50_95")}
    bestv = {m: max([v for v in vs if v is not None], default=None) for m, vs in allv.items()}
    for block, ids in MAIN_BLOCKS:
        for k, e in enumerate(ids):
            cells = [eid_tex(e), block, "nsmlx"[k]]
            for m in ("P", "R", "mAP50", "mAP50_95"):
                cell = pm(mv(e, m), mv(e, m, field="sd_folds"))
                v = num(mv(e, m))
                if v is not None and bestv[m] is not None and abs(v - bestv[m]) < 1e-12:
                    cell = f"\\textbf{{{cell}}}"
                cells.append(cell)
            lines.append(" & ".join(cells) + " \\\\")
        lines.append("\\hline")
    lines.append("\\end{tabular}")
    write(out / "tab_main.tex", "\n".join(lines))

    # ----------------------------------------------------------------- origin halves
    lines = ["\\begin{tabular}{@{}llcc@{}}", "\\hline",
             "\\textbf{\\#} & \\textbf{Training corpus} & \\textbf{Public (v1)} & \\textbf{Generated (v2)} \\\\",
             "\\hline"]
    labels = {"E3": "v1, m", "E8": "v2, m", "E13": "v3, m", "E19": "v3 size-m., m",
              "E20": "v3 deranged, m", "E18": "v3, Mask R-CNN"}
    for e in ORIGIN_IDS:
        lines.append(" & ".join([eid_tex(e), labels.get(e, e),
                                 pm(mv(e, "mAP50_95", "v1_origin"), mv(e, "mAP50_95", "v1_origin", "sd_folds")),
                                 pm(mv(e, "mAP50_95", "v2_origin"), mv(e, "mAP50_95", "v2_origin", "sd_folds"))]) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_origin.tex", "\n".join(lines))

    # ----------------------------------------------------------------- controls
    lines = ["\\begin{tabular}{@{}llcccc@{}}", "\\hline",
             "\\textbf{\\#} & \\textbf{Configuration} & \\textbf{P} & \\textbf{R} & \\textbf{mAP50} & \\textbf{mAP50-95} \\\\",
             "\\hline"]
    for e, lab in CONTROLS:
        lines.append(" & ".join([eid_tex(e), lab] + [pm(mv(e, m), mv(e, m, field="sd_folds"))
                                                     for m in ("P", "R", "mAP50", "mAP50_95")]) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_controls.tex", "\n".join(lines))

    # ----------------------------------------------------------------- comparisons
    lines = ["\\begin{tabular}{@{}llcccc@{}}", "\\hline",
             "\\textbf{Comparison} & \\textbf{Pair} & \\textbf{$\\Delta$mAP50-95} & \\textbf{95\\% CI} & "
             "\\textbf{$p$} & \\textbf{$p_{\\mathrm{Holm}}$} \\\\", "\\hline"]
    labels = {(x, y): lab for x, y, lab in COMPARISONS}
    order = {(x, y): i for i, (x, y, _) in enumerate(COMPARISONS)}
    pairs = [(x, y) for x, y, _ in COMPARISONS]
    pairs += sorted({(k[0], k[1]) for k in comp if k[2] == "common" and (k[0], k[1]) not in order})
    for x, y in pairs:
        r = comp.get((x, y, "common", "mAP50_95"), {})
        if not r:
            continue        # a declared pair whose configurations were not run
        p, ph = num(r.get("p_paired_t")), num(r.get("p_holm"))
        lab = labels.get((x, y), f"{eid_tex(x)} vs.\\ {eid_tex(y)}")
        lines.append(" & ".join([lab, f"{eid_tex(x)}$-${eid_tex(y)}", fsigned(r.get("delta")),
                                 f"[{fsigned(r.get('ci_low'))}, {fsigned(r.get('ci_high'))}]",
                                 TBD if p is None else ("$<$0.001" if p < 0.001 else f"{p:.3f}"),
                                 TBD if ph is None else ("$<$0.001" if ph < 0.001 else f"{ph:.3f}")]) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_comparisons.tex", "\n".join(lines))

    # ----------------------------------------------------------------- per class
    lines = ["\\begin{tabular}{@{}lr" + "c" * len(PERCLASS_IDS) + "@{}}", "\\hline",
             "\\textbf{Class} & \\textbf{$n$} & " + " & ".join(f"\\textbf{{{lab}}}" for _, lab in PERCLASS_IDS) + " \\\\",
             " & & " + " & ".join(eid_tex(e) for e, _ in PERCLASS_IDS) + " \\\\", "\\hline"]
    ngt = {}
    if proto:
        import statistics
        counts = [info["common_test"]["per_class"] for info in proto.get("folds", {}).values()
                  if "per_class" in info.get("common_test", {})]
        if counts:
            ngt = {c: statistics.mean([d.get(c, 0) for d in counts]) for c in names}
            for c, v in ngt.items():
                M.set("ngt", c, fint(v))
    for cls in names:
        cells = [disp(cls), fint(ngt.get(cls))]
        for e, _ in PERCLASS_IDS:
            r = per_class.get((e, "common", cls), {})
            cells.append(pm(r.get("mean"), r.get("sd_folds"), 3))
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_perclass.tex", "\n".join(lines))

    # ----------------------------------------------------------------- cost per scale
    lines = ["\\begin{tabular}{@{}lrrrrc@{}}", "\\hline",
             "\\textbf{Scale} & \\textbf{Par.\\,(M)} & \\textbf{GFLOPs} & \\textbf{MB} & \\textbf{ms} & \\textbf{mAP50-95} \\\\",
             "\\hline"]
    for e, s in SCALES:
        m = models.get(e, {})
        p = num(m.get("params"))
        lines.append(" & ".join([s, f"{p / 1e6:.1f}" if p else TBD, f(m.get("gflops"), 1), f(m.get("size_mb"), 1),
                                 f(m.get("latency_ms_median"), 1), f(mv(e, "mAP50_95"))]) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_cost.tex", "\n".join(lines))

    # ----------------------------------------------------------------- corpora and partitions
    lines = ["\\begin{tabular}{@{}lrr" + "r" * len(names) + "@{}}", "\\hline",
             " & \\textbf{Img.} & \\textbf{Inst.} & " + " & ".join(f"\\textbf{{{ABBR.get(n, n[:3])}}}" for n in names) + " \\\\",
             "\\hline"]
    for key in ("v1", "v2", "v3"):
        t = cstats.get(key, {}).get("total", {})
        pc = t.get("per_class", {})
        lines.append(" & ".join([key, fint(t.get("images")), fint(t.get("instances"))]
                                + [fint(pc.get(n, 0) if t else None) for n in names]) + " \\\\")
        if t:
            M.set(key, "images", fint(t["images"]))
            M.set(key, "instances", fint(t["instances"]))
            for n in names:
                M.set(key, f"inst_{n}", fint(pc.get(n, 0)))
                if t["instances"]:
                    M.set(key, f"share_{n}", fpct(pc.get(n, 0) / t["instances"]))
            M.set(key, "verts_median", fint(t["vertices"]["median"]))
            M.set(key, "box_lines", fint(t.get("box_lines")))
            M.set(key, "labelled_images", fint(t.get("labelled_images")))
            M.set(key, "verts_mean", f(t["vertices"]["mean"], 1))
            M.set(key, "multiclass_pct", fpct(t["multiclass_share"], 2))
            M.set(key, "inst_per_img", f(t["instances_per_image"]["mean"], 2))
            co = list(t.get("cooccurrence", {}).items())[:3]
            M.set(key, "top_cooccurrence", ", ".join(k.replace("+", " with ").replace("_", " ") for k, _ in co) if co else None)
            g = cstats[key].get("per_class_geometry", {})
            for cls in ("grey", "SIGRE"):
                if cls in g:
                    M.set(key, f"{cls}_mean_area", f(g[cls]["mean_area_norm"]))
                    M.set(key, f"{cls}_small_pct", fpct(g[cls]["small"], 0))
                    M.set(key, f"{cls}_large_pct", fpct(g[cls]["large"], 0))
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_composition.tex", "\n".join(lines))

    lines = ["\\begin{tabular}{@{}lrrr@{}}", "\\hline",
             "\\textbf{Corpus} & \\textbf{Train} & \\textbf{Validation} & \\textbf{Test} \\\\", "\\hline"]
    if proto:
        folds = proto.get("folds", {})
        import statistics
        for c in ("v1", "v2", "v3"):
            vals = {s: [info[c][s] for info in folds.values() if c in info and s in info[c]] for s in ("train", "val", "test")}
            lines.append(" & ".join([c] + [fint(statistics.mean(v)) if v else TBD for v in vals.values()]) + " \\\\")
            for s, v in vals.items():
                M.set(f"{c}_{s}", "images", fint(statistics.mean(v)) if v else None)
        ct = [info["common_test"]["images"] for info in folds.values() if "common_test" in info]
        ci = [info["common_test"].get("annotations_kept") for info in folds.values() if "common_test" in info]
        if ct:
            lines += ["\\hline", " & ".join(["Common test set", "--", "--", fint(statistics.mean(ct))]) + " \\\\"]
            M.set("protocol", "common_test", fint(statistics.mean(ct)))
            M.set("protocol", "common_test_min", fint(min(ct)))
            M.set("protocol", "common_test_max", fint(max(ct)))
            M.set("protocol", "common_test_total", fint(sum(ct)))
            M.set("protocol", "folds", fint(len(ct)))
            if any(ci):
                M.set("protocol", "common_test_instances", fint(statistics.mean([x for x in ci if x])))
        leak = [info.get("common_test_sharing_source_with_training") for info in folds.values()]
        leak = [x for x in leak if x is not None]
        if leak:
            M.set("protocol", "leak_mean", fint(statistics.mean(leak)))
            M.set("protocol", "leak_max", fint(max(leak)))
        sm = [info["sizematched"]["images"] for info in folds.values() if "sizematched" in info]
        if sm:
            M.set("protocol", "sizematched_images", fint(statistics.mean(sm)))
        dr = [info["deranged"] for info in folds.values() if "deranged" in info]
        if dr:
            M.set("protocol", "deranged_images", fint(statistics.mean([d["relabelled_images"] for d in dr])))
            M.set("protocol", "deranged_instances", fint(statistics.mean([d["relabelled_instances"] for d in dr])))
            M.set("protocol", "excluded_class", ", ".join(dr[0]["excluded"]))
    else:
        for c in ("v1", "v2", "v3"):
            lines.append(" & ".join([c, TBD, TBD, TBD]) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_splits.tex", "\n".join(lines))
    M.set("protocol", "runs_total", fint(sum(num(r.get("runs")) or 0 for r in models.values())))
    M.set("protocol", "configs", fint(len(models)))

    # geometry table
    def g(c, *path):
        d = cstats.get(c, {})
        for p in path:
            d = d.get(p, {}) if isinstance(d, dict) else {}
        return d or None
    lines = ["\\begin{tabular}{@{}lccc@{}}", "\\hline", " & \\textbf{v1} & \\textbf{v2} & \\textbf{v3} \\\\", "\\hline"]
    def ms(c, *path, d=1):
        x = g(c, *path)
        return f"${x['mean']:.{d}f} \\pm {x['sd']:.{d}f}$" if x and x.get("mean") is not None else TBD
    lines.append("Vertices, mean $\\pm$ SD & " + " & ".join(ms(c, "total", "vertices") for c in ("v1", "v2", "v3")) + " \\\\")
    lines.append("Vertices, median & " + " & ".join(fint((g(c, "total", "vertices") or {}).get("median")) for c in ("v1", "v2", "v3")) + " \\\\")
    lines.append("Instances per image & " + " & ".join(ms(c, "total", "instances_per_image", d=2) for c in ("v1", "v2", "v3")) + " \\\\")
    lines.append("Multi-class images (\\%) & " + " & ".join(fpct((g(c, "total") or {}).get("multiclass_share"), 2) for c in ("v1", "v2", "v3")) + " \\\\")
    for cls in ("grey", "SIGRE"):
        if cls not in names:
            continue
        lines += ["\\hline", f"\\multicolumn{{4}}{{@{{}}l}}{{\\textit{{{disp(cls)} class}}}} \\\\"]
        pcg = {c: (g(c, "per_class_geometry", cls) or {}) for c in ("v1", "v2", "v3")}
        lines.append("\\quad Instances & " + " & ".join(fint(pcg[c].get("instances")) for c in ("v1", "v2", "v3")) + " \\\\")
        lines.append("\\quad Mean area & " + " & ".join(f(pcg[c].get("mean_area_norm")) for c in ("v1", "v2", "v3")) + " \\\\")
        lines.append("\\quad S/M/L share (\\%) & " + " & ".join(
            (f"{100 * pcg[c]['small']:.0f}/{100 * pcg[c]['medium']:.0f}/{100 * pcg[c]['large']:.0f}" if pcg[c] else TBD)
            for c in ("v1", "v2", "v3")) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_geometry.tex", "\n".join(lines))

    # ----------------------------------------------------------------- pipeline, classifier, audit (unchanged sources)
    sweep = load_rows(R / "pipeline" / "pipeline_tau_sweep.csv")
    psum = load_json(R / "pipeline" / "pipeline_summary.json")
    # the agreement column needs the human image-level labels; without them it is left out
    has_agree = any(num(r.get("label_agreement")) is not None for r in sweep) or not sweep
    head = "\\textbf{$\\tau$} & \\textbf{Images} & \\textbf{Ret.\\,(\\%)} & \\textbf{Instances}" \
           + (" & \\textbf{Agr.\\,(\\%)}" if has_agree else "") + " \\\\"
    lines = ["\\begin{tabular}{@{}crrr" + ("r" if has_agree else "") + "@{}}", "\\hline", head, "\\hline"]
    if sweep:
        for r in sweep:
            cells = [ftau(r["tau"]), fint(r["images_retained"]), fpct(r["retention"]), fint(r["instances"])]
            if has_agree:
                cells.append(fpct(r["label_agreement"]) if num(r["images_retained"]) else "--")
            if r.get("operating") in ("True", "true", "1"):
                cells = [f"\\textbf{{{c}}}" for c in cells]
                M.set("pipe", "retained", fint(r["images_retained"]))
                M.set("pipe", "retention_pct", fpct(r["retention"]))
                M.set("pipe", "instances", fint(r["instances"]))
                M.set("pipe", "agreement_pct", fpct(r["label_agreement"]))
            lines.append(" & ".join(cells) + " \\\\")
    else:
        for tau_ in ("0.50", "0.70", "0.90", "0.95"):
            lines.append(" & ".join([tau_] + [TBD] * (4 if has_agree else 3)) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    write(out / "tab_pipeline.tex", "\n".join(lines))
    if sweep:
        vals = [(num(r["tau"]), num(r["images_retained"])) for r in sweep if num(r["images_retained"])]
        lo = [v for tau, v in vals if tau is not None and abs(tau - 0.5) < 1e-9]
        hi = [v for tau, v in vals if tau is not None and abs(tau - 0.99) < 1e-9]
        if lo and hi and lo[0]:
            M.set("pipe", "sweep_drop_pct", f"{100 * (lo[0] - hi[0]) / lo[0]:.1f}")
    if sweep:
        lo = num(sweep[0].get("images_retained"))
        op = next((num(r["images_retained"]) for r in sweep if r.get("operating") in ("True", "true", "1")), None)
        if lo and op:
            M.set("pipe", "retained_drop_pct", fpct((lo - op) / lo))
    if psum:
        M.set("pipe", "source_images", fint(psum["source_images"]))
        M.set("pipe", "agreement_all_pct", fpct(psum.get("classifier_agreement_all_images")))
        op = psum.get("operating", {})
        M.set("pipe", "conf", ftau(op.get("conf")) if op.get("conf") is not None else None)
        M.set("pipe", "eps", op.get("eps"))
        M.set("pipe", "min_area", fint(op.get("min_area")))
        M.set("pipe", "mask_thr", op.get("mask_thr"))
    cal = load_json(R / "pipeline" / "calibration.json")
    if cal:
        M.set("calib", "area_lo", fint(cal["min_area_range"][0]))
        M.set("calib", "area_hi", fint(cal["min_area_range"][1]))
        M.set("calib", "img_err_pct", fpct(cal.get("max_class_images_rel_error")))
        M.set("calib", "inst_err_pct", fpct(cal.get("max_class_instances_rel_error")))
        M.set("calib", "v2_verts_median", fint(cal["v2"]["vertices_median"]))

    cls_per = {r["class"]: r for r in load_rows(R / "classifier" / "classifier_per_class.csv")}
    csum = load_json(R / "classifier" / "classifier_summary.json")
    cov = load_rows(R / "classifier" / "classifier_coverage.csv")
    aud = {r["class"]: r for r in load_rows(R / "audit" / "audit_summary.csv")}
    lines = ["\\begin{tabular}{@{}lcccccc@{}}", "\\hline",
             " & \\multicolumn{2}{c}{\\textbf{Classifier}} & \\multicolumn{4}{c}{\\textbf{Audit}} \\\\",
             "\\cline{2-3}\\cline{4-7}",
             "\\textbf{Class} & \\textbf{P} & \\textbf{R} & \\textbf{$n$} & \\textbf{Acc.} & \\textbf{IoU} & \\textbf{B-IoU} \\\\",
             "\\hline"]
    macro = {}
    if cls_per:
        for fl in ("precision", "recall"):
            v = [num(r.get(fl)) for r in cls_per.values() if num(r.get(fl)) is not None]
            macro[fl] = sum(v) / len(v) if v else None
    for cls in names + ["all"]:
        c, d = cls_per.get(cls, {}), aud.get(cls, {})
        if cls == "all":
            lines.append("\\hline")
            c = macro
        lines.append(" & ".join([disp(cls) if cls != "all" else "All", f(c.get("precision"), 3), f(c.get("recall"), 3),
                                 fint(d.get("n_images")), f(d.get("label_accuracy"), 3), f(d.get("mask_iou"), 3),
                                 f(d.get("boundary_iou"), 3)]) + " \\\\")
    lines += ["\\hline", "\\end{tabular}"]
    # The table is written only when there is something in it. The manuscript guards both the
    # table and the sentences that quote it with \\IfFileExists, so a study without a classifier
    # split or without a manual audit still compiles into a finished paper instead of a grid of
    # question marks.
    write(out / "tab_labelquality.tex", "\n".join(lines))
    if not (cls_per or aud):
        print("no classifier or audit results yet: Table XV is written with ?? cells")
    for name, present in (("have_classifier", bool(cls_per)), ("have_audit", bool(aud))):
        marker = out / f"{name}.tex"
        if present:
            marker.write_text("% marker: the corresponding results exist\n")
        else:
            marker.unlink(missing_ok=True)
    if csum:
        M.set("cls", "top1_pct", fpct(csum["top1"]))
        M.set("cls", "macro_f1", f(csum.get("macro_f1"), 3))
        M.set("cls", "n", fint(csum["n"]))
        info = csum.get("classifier") or {}
        arch = str(info.get("architecture") or "").replace("_", "\\_")
        M.set("cls", "model", arch or None)
        M.set("cls", "imgsz", fint(info.get("imgsz")))
    if cov and psum:
        tau = num(psum.get("operating", {}).get("conf"))
        row = min(cov, key=lambda r: abs(float(r["tau"]) - tau)) if tau is not None else None
        if row and abs(float(row["tau"]) - tau) < 1e-9:
            M.set("cls", "acc_at_tau_pct", fpct(row["accuracy"]))
            M.set("cls", "coverage_at_tau_pct", fpct(row["coverage"]))
    if "all" in aud:
        d = aud["all"]
        for k, fl in (("n", "n_images"), ("n_manual", "n_with_manual")):
            M.set("audit", k, fint(d.get(fl)))
        M.set("audit", "mask_iou", f(d.get("mask_iou"), 3))
        M.set("audit", "boundary_iou", f(d.get("boundary_iou"), 3))
        M.set("audit", "label_acc_pct", fpct(d.get("label_accuracy")))
        M.set("audit", "inst_precision", f(d.get("instance_precision"), 3))
        M.set("audit", "inst_recall", f(d.get("instance_recall"), 3))

    for mf in sorted((R / "per_run").glob("*.json")) if (R / "per_run").exists() else []:
        env = (load_json(mf) or {}).get("environment", {})
        if env.get("gpu"):
            for k in ("python", "torch", "torchvision", "ultralytics", "cuda", "gpu", "gpu_mem_gb", "pycocotools"):
                M.set("env", k, env.get(k))
            break

    M.write(out / "results_macros.tex")
    print(f"Wrote {len(list(out.glob('tab_*.tex')))} table bodies and {len(M.items)} macros to {out}")


if __name__ == "__main__":
    main()
